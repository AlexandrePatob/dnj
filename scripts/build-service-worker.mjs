import { createHash } from "node:crypto";
import { access, mkdir, readFile, rename, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { build } from "esbuild";

const DEFAULT_ENTRY = "src/pwa/sw.ts";
const DEFAULT_POLICY = "src/pwa/cache-policy.ts";
const DEFAULT_OUTPUT = "public/sw.js";

function sanitizeRevision(value, limit) {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, limit);
}

export function resolveRevision(env, inputs) {
  if (env.VERCEL_GIT_COMMIT_SHA) {
    const commit = sanitizeRevision(env.VERCEL_GIT_COMMIT_SHA, 12);
    if (commit) return commit;
  }
  if (env.VERCEL_DEPLOYMENT_ID) {
    const deployment = sanitizeRevision(env.VERCEL_DEPLOYMENT_ID, 32);
    if (deployment) return deployment;
  }

  const digest = createHash("sha256");
  for (const input of inputs) digest.update(input).update("\0");
  return digest.digest("hex").slice(0, 12);
}

export async function writeFileAtomic(outputPath, contents) {
  const temporaryPath = `${outputPath}.${process.pid}.tmp`;
  await mkdir(path.dirname(outputPath), { recursive: true });

  try {
    await writeFile(temporaryPath, contents, "utf8");
    await rename(temporaryPath, outputPath);
    const written = await readFile(outputPath, "utf8");
    if (written !== contents) throw new Error(`Service worker write was incomplete: ${outputPath}`);
  } catch (error) {
    await rm(temporaryPath, { force: true });
    throw error;
  }
}

export async function buildServiceWorker({
  root = process.cwd(),
  entryPath = DEFAULT_ENTRY,
  outputPath = path.join(root, DEFAULT_OUTPUT),
  env = process.env,
} = {}) {
  const entry = path.isAbsolute(entryPath) ? entryPath : path.join(root, entryPath);
  const policy = path.join(root, DEFAULT_POLICY);

  try {
    await access(entry);
  } catch {
    throw new Error(`Service worker source not found: ${entry}`);
  }

  const inputs = await Promise.all([readFile(entry, "utf8"), readFile(policy, "utf8")]);
  const revision = resolveRevision(env, inputs);
  const result = await build({
    absWorkingDir: root,
    stdin: {
      contents: inputs[0],
      sourcefile: "src/pwa/sw.ts",
      loader: "ts",
    },
    plugins: [
      {
        name: "pwa-cache-policy",
        setup(buildContext) {
          buildContext.onResolve({ filter: /^\.\/cache-policy$/ }, () => ({
            path: "cache-policy.ts",
            namespace: "pwa-cache-policy",
          }));
          buildContext.onLoad({ filter: /.*/, namespace: "pwa-cache-policy" }, () => ({
            contents: inputs[1],
            loader: "ts",
          }));
        },
      },
    ],
    bundle: true,
    write: false,
    platform: "browser",
    format: "iife",
    target: "es2020",
    charset: "utf8",
    legalComments: "none",
    sourcemap: false,
    define: { __PWA_REVISION__: JSON.stringify(revision) },
  });

  if (result.outputFiles.length !== 1) throw new Error("Service worker bundle must produce exactly one file");
  const bundle = result.outputFiles[0].text;
  if (bundle.includes("__PWA_REVISION__")) throw new Error("Service worker bundle contains an unresolved revision placeholder");

  const header = [
    "/* Generated by scripts/build-service-worker.mjs.",
    " * This deployment artifact is versioned in git and regenerated by predev/prebuild.",
    ` * revision: ${revision}`,
    " */",
    `var revision = ${JSON.stringify(revision)};`,
  ].join("\n");
  const contents = `${header}\n${bundle}`;
  await writeFileAtomic(outputPath, contents);

  return { revision, outputPath, contents };
}

const invokedPath = process.argv[1] ? pathToFileURL(path.resolve(process.argv[1])).href : "";
if (invokedPath === import.meta.url) {
  await buildServiceWorker();
}
